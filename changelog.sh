#!/bin/bash

# Exit on any error
set -e

# Configuration - Change log file name
CHANGELOG_FILE="CHANGELOG.md"

# Get the last tag or default to initial commit
LAST_TAG=$(git describe --tags `git rev-list --tags --max-count=1` 2>/dev/null || echo "")

# If no tags found, get all commits
if [ -z "$LAST_TAG" ]; then
    COMMITS=$(git log --pretty=format:"%h %s %an %ad" --date=short)
else
    COMMITS=$(git log $LAST_TAG..HEAD --pretty=format:"%h %s %an %ad" --date=short)
fi

# Function to determine change type from commit message
categorize_commit() {
    local commit_message="$1"
    case "$commit_message" in
        *fix*|*Fix*|*FIX*)
            echo "Fixed"
            ;;
        *remove*|*delete*|*Remove*|*Delete*|*REMOVE*|*DELETE*)
            echo "Removed"
            ;;
        *change*|*update*|*refactor*|*Change*|*Update*|*Refactor*|*CHANGE*|*UPDATE*|*REFACTOR*)
            echo "Changed"
            ;;
        *)
            echo "Added"
            ;;
    esac
}

# Start the changelog with header
{
    echo "# Changelog"
    echo ""
    echo "## Changes"
    echo ""
} > $CHANGELOG_FILE

# Create temporary files for each category
> added.tmp
> fixed.tmp
> changed.tmp
> removed.tmp

# Process each commit
while IFS= read -r line; do
    if [ -n "$line" ]; then
        HASH=$(echo "$line" | awk '{print $1}')
        AUTHOR=$(echo "$line" | awk '{for(i=3;i<=NF;i++) if($i=="by") {for(j=1;j<i-1;j++) printf "%s%s", $j, (j<i-2)?" ":"\n"} }')
        DATE=$(echo "$line" | awk '{for(i=1;i<=NF;i++) if($i=="by") print $(i+1)}')
        MESSAGE=$(echo "$line" | cut -d' ' -f2-)
        
        CATEGORY=$(categorize_commit "$MESSAGE")
        echo "- $MESSAGE (commit $HASH)" >> "${CATEGORY,,}".tmp
    fi
done <<< "$(echo "$COMMITS" | grep -v "^$")"

# Add each category to changelog if it has content
for category in Added Fixed Changed Removed; do
    if [ -s "${category,,}".tmp ]; then
        echo "### $category" >> $CHANGELOG_FILE
        cat "${category,,}".tmp >> $CHANGELOG_FILE
        echo "" >> $CHANGELOG_FILE
    fi
done

{
    echo ""
    echo "<!-- Generated by Claude Changelog Generator -->"
    echo "<!-- Command: /generate-changelog -->"
} >> $CHANGELOG_FILE

# Cleanup temporary files
rm -f *.tmp

echo "Changelog generated in $CHANGELOG_FILE"