#!/usr/bin/env bash
set -euo pipefail

# changelog.sh — Generate a structured CHANGELOG.md from git history
# Usage: bash changelog.sh

REPO_URL=""
OUTPUT_FILE="CHANGELOG.md"

# Colors for terminal output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# Helper: print error and exit
die() {
    echo -e "${RED}Error: $1${NC}" >&2
    exit 1
}

# Check if we're in a git repo
if ! git rev-parse --git-dir > /dev/null 2>&1; then
    die "Not a git repository. Please run this script from a git repository."
fi

# Get the latest tag, or empty if no tags exist
LATEST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "")

# Get repo URL from git remote
get_repo_url() {
    local remote_url
    remote_url=$(git remote get-url origin 2>/dev/null || echo "")
    # Convert SSH URL to HTTPS if needed
    if [[ "$remote_url" == git@github.com:* ]]; then
        remote_url=$(echo "$remote_url" | sed 's|git@github.com:|https://github.com/|')
    fi
    # Remove .git suffix
    remote_url=$(echo "$remote_url" | sed 's/\.git$//')
    echo "$remote_url"
}

REPO_URL=$(get_repo_url)

# Get commits since last tag (or all commits if no tag)
get_commits() {
    if [ -n "$LATEST_TAG" ]; then
        git log "$LATEST_TAG"..HEAD --pretty=format:"%H|%s|%b" --no-merges
    else
        git log --pretty=format:"%H|%s|%b" --no-merges
    fi
}

# Categorize a commit based on its message
categorize_commit() {
    local msg="$1"
    local lower_msg
    lower_msg=$(echo "$msg" | tr '[:upper:]' '[:lower:]')
    
    # Check for conventional commit prefixes first
    if [[ "$lower_msg" =~ ^feat(\(.+\))?: ]]; then
        echo "added"
    elif [[ "$lower_msg" =~ ^fix(\(.+\))?: ]]; then
        echo "fixed"
    elif [[ "$lower_msg" =~ ^(chore|refactor|perf|style|docs|test|build|ci|revert)(\(.+\))?: ]]; then
        echo "changed"
    elif [[ "$lower_msg" =~ ^remove(\(.+\))?: || "$lower_msg" =~ ^delete(\(.+\))?: || "$lower_msg" =~ ^drop(\(.+\))?: ]]; then
        echo "removed"
    else
        # Fallback: keyword-based categorization
        if [[ "$lower_msg" =~ (add|new|introduce|implement|create|support|enable) ]]; then
            echo "added"
        elif [[ "$lower_msg" =~ (fix|bug|repair|resolve|patch|correct) ]]; then
            echo "fixed"
        elif [[ "$lower_msg" =~ (remove|delete|drop|eliminate|deprecate) ]]; then
            echo "removed"
        else
            echo "changed"
        fi
    fi
}

# Generate the changelog
generate_changelog() {
    local commits
    commits=$(get_commits)
    
    if [ -z "$commits" ]; then
        echo -e "${YELLOW}No commits found since last tag.${NC}"
        exit 0
    fi
    
    local added=()
    local fixed=()
    local changed=()
    local removed=()
    
    while IFS='|' read -r hash subject body; do
        [ -z "$hash" ] && continue
        
        local category
        category=$(categorize_commit "$subject")
        local entry="- $subject"
        
        # Add commit link if repo URL is available
        if [ -n "$REPO_URL" ]; then
            entry="- $subject ([\`$hash\`]($REPO_URL/commit/$hash))"
        fi
        
        case "$category" in
            added)  added+=("$entry") ;;
            fixed)  fixed+=("$entry") ;;
            removed) removed+=("$entry") ;;
            changed) changed+=("$entry") ;;
        esac
    done <<< "$commits"
    
    # Write CHANGELOG.md
    {
        echo "# Changelog"
        echo ""
        echo "All notable changes to this project will be documented in this file."
        echo ""
        echo "## [Unreleased]"
        echo ""
        
        if [ ${#added[@]} -gt 0 ]; then
            echo "### Added"
            printf '%s\n' "${added[@]}"
            echo ""
        fi
        
        if [ ${#fixed[@]} -gt 0 ]; then
            echo "### Fixed"
            printf '%s\n' "${fixed[@]}"
            echo ""
        fi
        
        if [ ${#changed[@]} -gt 0 ]; then
            echo "### Changed"
            printf '%s\n' "${changed[@]}"
            echo ""
        fi
        
        if [ ${#removed[@]} -gt 0 ]; then
            echo "### Removed"
            printf '%s\n' "${removed[@]}"
            echo ""
        fi
        
        echo "---"
        echo ""
        echo "*Generated by [changelog.sh](https://github.com/claude-builders-bounty/claude-builders-bounty)*"
    } > "$OUTPUT_FILE"
    
    echo -e "${GREEN}✓ CHANGELOG.md generated successfully!${NC}"
    echo -e "  Found: ${#added[@]} added, ${#fixed[@]} fixed, ${#changed[@]} changed, ${#removed[@]} removed"
}

# Main
echo "🔍 Generating changelog..."
if [ -n "$LATEST_TAG" ]; then
    echo "   Last tag: $LATEST_TAG"
else
    echo "   No tags found — using all commits"
fi

generate_changelog