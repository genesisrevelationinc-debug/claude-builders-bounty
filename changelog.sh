#!/bin/bash

# Script to generate a structured CHANGELOG.md from git history

# Function to get the latest tag
get_latest_tag() {
    local latest_tag=$(git describe --tags `git rev-list --tags --max-count=1`)
    if [ -z "$latest_tag" ]; then
        # If no tags found, use the first commit
        echo $(git rev-list --max-parents=0 HEAD)
    else
        echo $latest_tag
    fi
}

# Get the last tag or initial commit
LAST_TAG=$(get_latest_tag)

# If no tags exist, git describe will fail, so we handle it
if [ -z "$LAST_TAG" ]; then
    LAST_TAG=$(git rev-list --max-parents=0 HEAD)
fi

# Get commit messages from last tag to HEAD
COMMITS_SINCE_TAG=$(git log $LAST_TAG..HEAD --oneline)

# If no new commits since last tag, exit gracefully
if [ -z "$COMMITS_SINCE_TAG" ];
then
    echo "# Changelog" > CHANGELOG.md
    echo "" >> CHANGELOG.md
    echo "## (No changes detected since last tag)" >> CHANGELOG.md
    echo "" >> CHANGELOG.md
    echo "This file was generated by the changelog generator tool." >> CHANGECRLOG.md
    exit 0
fi

# Categorize commits and generate changelog
echo "# Changelog" > CHANGELOG.md
echo "" >> CHANGELOG.md

# Classify commits
while IFS= read -r line; do
    if [ -z "$line" ]; then
        continue
    fi
    
    # Extract commit message
    commit_msg=$(echo $line | sed 's/^[^ ]*[[:space:]]//')
    
    # Categorize based on keywords
    if [[ $commit_msg =~ ^([^:]*):[[:space:]]*(.*)$ ]]; then
        module="${BASH_REMATCH[1]}"
        message="${BASH_REMATCH[2]}"
        
        case "$module" in
            "feat" | "add" | "new" | "feature")
                echo "## [Added] $message" >> CHANGELOG.md
                ;;
            "fix" | "bug")
                echo "## [Fixed] $message" >> CHANGELOG.md
                ;;
            "change" | "update" | "update")
                echo "## [Changed] $message" >> CHANGELOG.md
                ;;
            "remove" | "rm" | "delete")
                echo "## [Removed] $message" >> CHANGELOG.md
                ;;
            *)
                echo "## [Changed] $message" >> CHANGELOG.md
                ;;
        esac
    else
        # Default case when no prefix
        echo "## [Changed] $line" >> CHANGELOG.md
    fi
done <<< "$COMMITS_SINCE_TAG"

echo "" >> CHANGELOG.md
echo "This file was generated by the changelog generator tool." >> CHANGELOG.md