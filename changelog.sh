#!/bin/bash

# changelog.sh - Generate a structured CHANGELOG.md from git history
#
# This script automatically generates a CHANGELOG.md file by analyzing
# git commit history since the last tag. Commits are categorized based
# on their prefixes (e.g., feat:, fix:, etc.).
#
# Usage:
#   ./changelog.sh
#
# Requirements:
#   - Git
#   - Standard Unix tools (sed, awk, grep, etc.)

set -e  # Exit on any error

# Configuration
CHANGELOG_FILE="CHANGELOG.md"
TMP_FILE="/tmp/changelog.tmp"

# Get the latest tag or default to initial commit
LATEST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "")
if [ -z "$LATEST_TAG" ]; then
    COMMIT_RANGE=""
    echo "No tags found. Processing all commits."
else
    COMMIT_RANGE="$LATEST_TAG..HEAD"
    echo "Processing commits since tag: $LATEST_TAG"
fi

# Create temporary file
> "$TMP_FILE"

# Initialize sections
ADDED=""
FIXED=""
CHANGED=""
REMOVED=""

# Process commits
if [ -z "$COMMIT_RANGE" ]; then
    # No tags - process all commits
    COMMITS=$(git log --pretty=format:"%s" 2>/dev/null)
else
    # Process commits since last tag
    COMMITS=$(git log --pretty=format:"%s" $COMMIT_RANGE 2>/dev/null)
fi

# Categorize commits
while IFS= read -r line; do
    case "$line" in
        feat:*|add:*)
            line=${line#*: }
            ADDED="$ADDED- ${line:0:1}${line:1}\n"
            ;;
        fix:*)
            line=${line#*: }
            FIXED="$FIXED- ${line:0:1}${line:1}\n"
            ;;
        change:*|refactor:*|update:*)
            line=${line#*: }
            CHANGED="$CHANGED- ${line:0:1}${line:1}\n"
            ;;
        remove:*|delete:*)
            line=${line#*: }
            REMOVED="$REMOVED- ${line:0:1}${line:1}\n"
            ;;
        *)
            # Default to Added for uncategorized commits
            ADDED="$ADDED- $line\n"
            ;;
    esac
done <<< "$COMMITS"

# Write to changelog file
{
    echo "# Changelog"
    echo ""
    echo "All notable changes to this project will be documented in this file."
    echo ""
    echo "## [Unreleased]"
    echo ""
    
    if [ -n "$ADDED" ]; then
        echo "### Added"
        echo -e "$ADDED"
    fi
    
    if [ -n "$FIXED" ]; then
        echo "### Fixed"
        echo -e "$FIXED"
    fi
    
    if [ -n "$CHANGED" ]; then
        echo "### Changed"
        echo -e "$CHANGED"
    fi
    
    if [ -n "$REMOVED" ]; then
        echo "### Removed"
        echo -e "$REMOVED"
    fi
    
    echo ""
    echo "[//]: # (Generated by changelog.sh - last run: $(date +%Y-%m-%d))"
} > "$CHANGELOG_FILE"

# Cleanup
rm -f "$TMP_FILE"

echo "CHANGELOG.md has been updated."