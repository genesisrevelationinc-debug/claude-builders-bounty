#!/bin/bash

# Get the latest git tag
latest_tag=$(git describe --tags `git rev-list --tags --max-count=1` 2>/dev/null)

# If no tags exist, set the latest_tag to a reasonable default
if [ -z "$latest_tag" ]; then
  # If no tags exist, use the root commit
  first_commit=$(git rev-list --max-parents=0 HEAD)
  last_tag=$first_commit
else
  # Get commit has associated with the last tag
  last_tag=$(git rev-list -n 1 $latest_tag)
fi

# Get commits between last tag and now
if [ -n "$last_tag" ]; then
  # Get commit titles between last tag and now
  commit_titles=$(git log --pretty=format:"%s" $last_tag..HEAD)
  # Get commit bodies between last tag and now
  commit_messages=$(git log --pretty=format:"%b" $last_tag..HEAD)
else
  commit_titles=$(git log --pretty=format:"%s" $first_commit..HEAD)
  commit_messages=$(git log --pretty=format:"%b")
fi

# Categorize commits
added_commits=""
fixed_commits=""
changed_commits=""
removed_commits=""

process_commit() {
  local commit_title="$1"
  local commit_message="$2"
  local category="$3"
  local commit_hash="$4"

  # Determine category from commit message
  if [[ $commit_title == *"add"* ]] || [[ $commit_title == *"feature"* ]] || [[ $commit_title == *"new"* ]] || [[ $commit_title == *"implement"* ]] || [[ $commit_title == *"create"* ]]; then
    category="Added"
  elif [[ $commit_title == *"fix"* ]] || [[ $commit_title == *"resolve"* ]] || [[ $commit_title == *"resolve"* ]] || [[ $commit_title == *"close"* ]] || [[ $commit_title == *"bug"* ]]; then
    category="Fixed"
  elif [[ $commit_title == *"remove"* ]] || [[ $commit_title == *"delete"* ]] || [[ $commit_title == *"deprecate"* ]] || [[ $commit_title == *"remove"* ]]; then
    category="Removed"
  else
    category="Changed"
  fi

  # Write to the appropriate category
  case "$category" in
    "Added")
      added_commits="$added_commits
- $commit_title [$commit_hash]($commit_hash)
"
      ;;
    "Fixed")
      fixed_commits="$fixed_commits
- $commit_title [$commit_hash]($commit_hash)
"
      ;;
    "Changed")
      changed_commits="$changed_commits
- $commit_title [$commit_hash]($commit_hash)
"
      ;;
    "Removed")
      removed_commits="$removed_commits
- $commit_title [$commit_hash]($commit_hash)
"
      ;;
  esac
}

echo "Processing commits..."
while IFS= read -r commit_line; do
  IFS='|' read -r commit_title commit_hash <<< "$commit_line"
  process_commit "$commit_title" "$commit_hash" "Changed" "$commit_hash"
done < <(git log --pretty=format:"%s|%h" $last_tag..HEAD)

# Generate the changelog
{
  echo "# Changelog"
  echo ""
  echo "## Added"
  echo "$added_commits"
  echo ""
  echo "## Fixed"
  echo "$fixed_commits"
  echo ""
  echo "## Changed"
  echo "$changed_commits"
  echo ""
  echo "## Removed" 
  echo "$removed_commits"
  echo ""
  echo "[//]: # (Changelog generated by changelog.sh)"
} > CHANGELOG.md

echo "Done! Changelog generated in CHANGELOG.md"
